public class Attributes {
    String fname = "Amirah";
    String lname = "Shaik";
    int age = 22;
    public static void main(String[] args) {
        Attributes myObj = new Attributes();
        System.out.println("Name: " + myObj.fname + " " + myObj.lname);
        System.out.println("Age: " + myObj.age);
    }
}
